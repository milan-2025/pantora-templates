/** Text the product was created with ("headline for workout challange", "text 1", "emoji 2", "3" …). */
export const isPlaceholder = (v: unknown): boolean =>
  typeof v === "string" && /(^|\s)(for|of) workout challange$|^(text|emoji|title|question|answer|label|name) ?\d+$|^\d$/i.test(v.trim());

/**
 * Sections of the product the new copy doesn't cover (e.g. showcase, highlights, testimonials,
 * contact, preview) are cleaned: placeholder strings are emptied and array rows made only of
 * placeholders are removed. Anything real is left as it is.
 */
export function cleanPlaceholders<T>(value: T, changes: string[], where = ""): T {
  if (Array.isArray(value)) {
    const kept = value
      .map((v, i) => cleanPlaceholders(v, changes, `${where}[${i}]`))
      .filter((v) => {
        if (v === "" || v === null) return false;
        if (v && typeof v === "object") {
          const vals = Object.entries(v).filter(([k]) => k !== "id").map(([, x]) => x);
          return vals.some((x) => x !== "" && x !== null && x !== undefined && !(Array.isArray(x) && !x.length));
        }
        return true;
      });
    if (kept.length !== value.length) changes.push(`${where}: removed ${value.length - kept.length} placeholder row(s)`);
    return kept as T;
  }
  if (isPlaceholder(value)) {
    changes.push(`${where}: cleared "${value}"`);
    return "" as T;
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, cleanPlaceholders(v, changes, where ? `${where}.${k}` : k)])) as T;
  }
  return value;
}

type Doc = Record<string, unknown>;

/** Works out the update for the product: the new copy, plus placeholder clean-up of every other section. */
export function planWorkoutUpdate(product: Doc): { data: Doc; changes: string[] } {
  const changes: string[] = [];
  const data: Doc = {};
  const ours = WORKOUT_FIELDS as unknown as Doc;
  for (const [k, v] of Object.entries(ours)) {
    if (JSON.stringify(product[k]) !== JSON.stringify(v)) changes.push(`${k}: new copy`);
    data[k] = Array.isArray(v) || typeof v !== "object" ? v : { ...((product[k] as Doc) ?? {}), ...(v as Doc) };
  }
  for (const k of ["showcase", "highlights", "testimonials", "contact", "finalCta", "preview", "bonus", "salesCounter", "offer"]) {
    if (product[k] == null) continue;
    const base = (data[k] as Doc) ?? product[k];
    const cleaned = cleanPlaceholders(base, changes, k);
    if (JSON.stringify(cleaned) !== JSON.stringify(product[k])) data[k] = cleaned;
  }
  return { data, changes };
}
